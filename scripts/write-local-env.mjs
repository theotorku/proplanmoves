/**
 * Writes .env.local from the running local Supabase stack.
 *
 * The dev server and the E2E run both need real keys, and the local stack mints
 * them on start. Reading them from `supabase status` keeps the file in step
 * with whatever is actually running instead of a copied snapshot that silently
 * goes stale.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const envPath = join(process.cwd(), ".env.local");
const force = process.argv.includes("--force");

if (existsSync(envPath) && !force) {
  const existing = readFileSync(envPath, "utf8");
  if (existing.includes("NEXT_PUBLIC_SUPABASE_URL")) {
    console.log(".env.local already exists; pass --force to rewrite it.");
    process.exit(0);
  }
}

let status;

try {
  status = execFileSync("npx", ["--yes", "supabase", "status", "-o", "json"], {
    encoding: "utf8",
    shell: process.platform === "win32"
  });
} catch (error) {
  console.error(
    "Could not read the local Supabase status. Start it first with `npm run db:start`."
  );
  console.error(error.stderr?.toString() ?? error.message);
  process.exit(1);
}

const parsed = JSON.parse(status);
const apiUrl = parsed.API_URL;
const anonKey = parsed.ANON_KEY;
const serviceRoleKey = parsed.SERVICE_ROLE_KEY;

if (!apiUrl || !anonKey || !serviceRoleKey) {
  console.error("The local Supabase status did not include the expected keys.");
  process.exit(1);
}

const contents = [
  "# Generated by scripts/write-local-env.mjs for local development and E2E.",
  "# These are local-stack keys only. Never put production secrets here.",
  "NEXT_PUBLIC_APP_URL=http://127.0.0.1:3000",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
  "BOOTSTRAP_OWNER_EMAIL=owner@proplanmoves.test",
  "BUSINESS_TIMEZONE=America/Chicago",
  "DEFAULT_CURRENCY=USD",
  "LOG_LEVEL=info",
  ""
].join("\n");

writeFileSync(envPath, contents, "utf8");
console.log(`Wrote ${envPath}`);
